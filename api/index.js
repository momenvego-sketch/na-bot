async function answerCallback(callbackQuery) {

  if (!TOKEN) {
    console.error("BOT_TOKEN is missing");
    return;
  }

  try {

    await fetch(
      `${TELEGRAM_API}/answerCallbackQuery`,
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json"
        },
        body: JSON.stringify({
          callback_query_id: callbackQuery.id
        })
      }
    );

  } catch (error) {

    console.error(
      "answerCallback ERROR:",
      error
    );

  }
}

